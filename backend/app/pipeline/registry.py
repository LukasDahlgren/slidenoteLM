from __future__ import annotations

from pathlib import Path
from typing import Callable

from ..config import Settings
from ..schemas import (
    ARTIFACT_ALIGNMENT,
    ARTIFACT_NOTES_MD,
    ARTIFACT_SLIDES_OCR,
    ARTIFACT_TRANSCRIPT,
    AlignmentArtifact,
    JobContext,
    PipelineStage,
    SlidesOCRArtifact,
    StageError,
    StageResult,
    TranscriptArtifact,
)

StageHandler = Callable[[JobContext, Settings], StageResult]


def _placeholder_audio_prep_stage(context: JobContext, _settings: Settings) -> StageResult:
    if not context.recording_path.exists():
        raise StageError(
            stage="audio_prep",
            message="Uploaded recording file is missing from job storage.",
            hint="Re-upload the slide PDF and recording to start a fresh job.",
        )
    return StageResult(
        message="Audio prep placeholder completed (Phase 2 adds ffmpeg normalization).",
    )


def _placeholder_transcription_stage(context: JobContext, settings: Settings) -> StageResult:
    artifact = TranscriptArtifact(
        source_recording=context.recording_filename,
        model=settings.transcription_model,
        duration_seconds=0.0,
        segments=[],
    )
    context.transcript_path.write_text(artifact.model_dump_json(indent=2), encoding="utf-8")
    return StageResult(
        message="Transcription placeholder completed (Phase 2 adds Groq Whisper).",
        artifacts={"transcript": ARTIFACT_TRANSCRIPT},
        stats={"duration_seconds": 0.0, "transcript_segments": 0},
    )


def _placeholder_ocr_stage(context: JobContext, settings: Settings) -> StageResult:
    if not context.slides_path.exists():
        raise StageError(
            stage="ocr",
            message="Uploaded slide PDF is missing from job storage.",
            hint="Re-upload the slide PDF and recording to start a fresh job.",
        )
    artifact = SlidesOCRArtifact(
        source_pdf=context.slides_filename,
        model=settings.ocr_model_google,
        slide_count=0,
        slides=[],
    )
    context.slides_ocr_path.write_text(artifact.model_dump_json(indent=2), encoding="utf-8")
    return StageResult(
        message="Slide OCR placeholder completed (Phase 3 adds strict Gemini OCR).",
        artifacts={"slides_ocr": ARTIFACT_SLIDES_OCR},
        stats={"slide_count": 0},
    )


def _placeholder_alignment_stage(context: JobContext, settings: Settings) -> StageResult:
    artifact = AlignmentArtifact(
        mode=settings.pipeline_llm_mode,
        entries=[],
        alignment_issues=[],
    )
    context.alignment_path.write_text(artifact.model_dump_json(indent=2), encoding="utf-8")
    return StageResult(
        message="Alignment placeholder completed (Phase 4 adds alignment scaffolding).",
        artifacts={"alignment": ARTIFACT_ALIGNMENT},
    )


def _placeholder_notes_stage(context: JobContext, settings: Settings) -> StageResult:
    title = Path(context.slides_filename).stem or "Lecture Notes"
    markdown = "\n".join(
        [
            f"# {title}",
            "",
            "> Placeholder output generated by the Phase 1 backend skeleton.",
            f"> Mode: `{settings.pipeline_llm_mode}`",
            "",
            "## Uploaded Sources",
            f"- Slides PDF: `{context.slides_filename}`",
            f"- Recording: `{context.recording_filename}`",
            "",
            "## Next Pipeline Phases",
            "- Phase 2 will add ffmpeg audio normalization and Groq Whisper transcription.",
            "- Phase 3 will add strict Google Gemini slide OCR.",
            "- Phase 4 will add alignment checks and AI-first NotebookLM Markdown generation.",
            "",
        ]
    )
    context.notes_path.write_text(markdown, encoding="utf-8")
    return StageResult(
        message="Markdown notes ready for download.",
        artifacts={"notes_md": ARTIFACT_NOTES_MD},
        stats={"word_count": len(markdown.split())},
    )


def build_default_stage_handlers() -> dict[PipelineStage, StageHandler]:
    """Return the active pipeline stage handlers; Phases 2-4 replace each stage here."""
    return {
        "audio_prep": _placeholder_audio_prep_stage,
        "transcription": _placeholder_transcription_stage,
        "ocr": _placeholder_ocr_stage,
        "alignment": _placeholder_alignment_stage,
        "notes": _placeholder_notes_stage,
    }
