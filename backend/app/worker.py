from __future__ import annotations

import json
import logging
import threading
from concurrent.futures import Future, ThreadPoolExecutor
from pathlib import Path
from typing import Callable

from .config import Settings
from .db import JobStore
from .schemas import (
    BACKGROUND_STAGES,
    STAGE_LABELS,
    JobContext,
    PipelineStage,
    StageError,
    StageResult,
)

logger = logging.getLogger(__name__)

StageHandler = Callable[[JobContext, Settings], StageResult]


def _default_audio_prep_stage(context: JobContext, _settings: Settings) -> StageResult:
    if not context.recording_path.exists():
        raise StageError(
            stage="audio_prep",
            message="Uploaded recording file is missing from job storage.",
            hint="Re-upload the slide PDF and recording to start a fresh job.",
        )
    return StageResult(
        message="Audio prep placeholder completed (Phase 2 adds ffmpeg normalization).",
    )


def _default_transcription_stage(context: JobContext, _settings: Settings) -> StageResult:
    transcript_path = context.artifacts_dir / "transcript.json"
    payload = {
        "mode": "placeholder",
        "source_recording": context.recording_filename,
        "segments": [],
    }
    transcript_path.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    return StageResult(
        message="Transcription placeholder completed (Phase 2 adds Groq Whisper).",
        artifacts={"transcript": "artifacts/transcript.json"},
    )


def _default_ocr_stage(context: JobContext, _settings: Settings) -> StageResult:
    if not context.slides_path.exists():
        raise StageError(
            stage="ocr",
            message="Uploaded slide PDF is missing from job storage.",
            hint="Re-upload the slide PDF and recording to start a fresh job.",
        )
    ocr_path = context.artifacts_dir / "slides_ocr.json"
    payload = {
        "mode": "placeholder",
        "source_pdf": context.slides_filename,
        "slides": [],
    }
    ocr_path.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    return StageResult(
        message="Slide OCR placeholder completed (Phase 3 adds strict Gemini OCR).",
        artifacts={"slides_ocr": "artifacts/slides_ocr.json"},
    )


def _default_alignment_stage(context: JobContext, _settings: Settings) -> StageResult:
    alignment_path = context.artifacts_dir / "alignment.json"
    payload = {
        "mode": "placeholder",
        "entries": [],
        "alignment_issues": [],
    }
    alignment_path.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    return StageResult(
        message="Alignment placeholder completed (Phase 4 adds alignment scaffolding).",
        artifacts={"alignment": "artifacts/alignment.json"},
    )


def _default_notes_stage(context: JobContext, settings: Settings) -> StageResult:
    notes_path = context.artifacts_dir / "notes.md"
    title = Path(context.slides_filename).stem or "Lecture Notes"
    markdown = "\n".join(
        [
            f"# {title}",
            "",
            "> Placeholder output generated by the Phase 1 backend skeleton.",
            f"> Mode: `{settings.pipeline_llm_mode}`",
            "",
            "## Uploaded Sources",
            f"- Slides PDF: `{context.slides_filename}`",
            f"- Recording: `{context.recording_filename}`",
            "",
            "## Next Pipeline Phases",
            "- Phase 2 will add ffmpeg audio normalization and Groq Whisper transcription.",
            "- Phase 3 will add strict Google Gemini slide OCR.",
            "- Phase 4 will add alignment checks and AI-first NotebookLM Markdown generation.",
            "",
        ]
    )
    notes_path.write_text(markdown, encoding="utf-8")
    return StageResult(
        message="Markdown notes ready for download.",
        artifacts={"notes_md": "artifacts/notes.md"},
    )


def build_default_stage_handlers() -> dict[PipelineStage, StageHandler]:
    return {
        "audio_prep": _default_audio_prep_stage,
        "transcription": _default_transcription_stage,
        "ocr": _default_ocr_stage,
        "alignment": _default_alignment_stage,
        "notes": _default_notes_stage,
    }


class JobWorker:
    """Runs lecture processing jobs asynchronously in a background thread pool."""

    def __init__(
        self,
        store: JobStore,
        settings: Settings,
        stage_handlers: dict[PipelineStage, StageHandler] | None = None,
    ) -> None:
        self.store = store
        self.settings = settings
        self._handlers: dict[PipelineStage, StageHandler] = build_default_stage_handlers()
        if stage_handlers:
            self._handlers.update(stage_handlers)
        self._executor = ThreadPoolExecutor(
            max_workers=settings.worker_concurrency,
            thread_name_prefix="slidenotelm-worker",
        )
        self._lock = threading.Lock()
        self._futures: dict[str, Future[None]] = {}

    def recover_interrupted_jobs(self) -> int:
        count = self.store.mark_interrupted_jobs()
        if count:
            logger.warning("Marked %d interrupted job(s) as failed on startup.", count)
        return count

    def submit(self, token: str) -> Future[None]:
        future = self._executor.submit(self.run_job, token)
        with self._lock:
            self._futures[token] = future

        def _cleanup(_done: Future[None]) -> None:
            with self._lock:
                self._futures.pop(token, None)

        future.add_done_callback(_cleanup)
        return future

    def wait_for_job(self, token: str, timeout: float = 10.0) -> None:
        with self._lock:
            future = self._futures.get(token)
        if future is not None:
            future.result(timeout=timeout)

    def run_job(self, token: str) -> None:
        job = self.store.get_job(token)
        if job is None:
            logger.error("Cannot run unknown job token=%s", token)
            return

        job_dir = Path(job["job_dir"])
        input_dir = job_dir / "input"
        artifacts_dir = job_dir / "artifacts"
        artifacts_dir.mkdir(parents=True, exist_ok=True)

        artifacts: dict[str, str] = dict(job.get("artifacts") or {})
        slides_rel = artifacts.get("slides_pdf", "input/slides.pdf")
        recording_rel = artifacts.get("recording", "")
        slides_path = job_dir / slides_rel
        recording_path = job_dir / recording_rel if recording_rel else input_dir / "recording"

        self.store.mark_job_started(token)

        for stage in BACKGROUND_STAGES:
            handler = self._handlers[stage]
            self.store.start_stage(token, stage)
            context = JobContext(
                token=token,
                slides_filename=str(job["slides_filename"]),
                recording_filename=str(job["recording_filename"]),
                job_dir=job_dir,
                input_dir=input_dir,
                artifacts_dir=artifacts_dir,
                slides_path=slides_path,
                recording_path=recording_path,
                artifacts=dict(artifacts),
            )
            try:
                result = handler(context, self.settings)
            except StageError as exc:
                logger.warning(
                    "Job %s failed at stage %s: %s",
                    token,
                    exc.stage,
                    exc.message,
                )
                self.store.mark_job_failed(
                    token,
                    stage=exc.stage,
                    message=exc.message,
                    hint=exc.hint,
                )
                return
            except Exception as exc:  # pragma: no cover - defensive catch-all
                logger.exception("Unexpected error in job %s at stage %s", token, stage)
                stage_label = STAGE_LABELS[stage]
                self.store.mark_job_failed(
                    token,
                    stage=stage,
                    message=f"Unexpected error during {stage_label}: {exc}",
                    hint="Check backend server logs and retry the upload.",
                )
                return

            if result.artifacts:
                artifacts.update(result.artifacts)
            self.store.complete_stage(
                token,
                stage,
                message=result.message or f"{STAGE_LABELS[stage]} completed.",
                artifacts=result.artifacts or None,
            )

        self.store.mark_job_completed(token, artifacts=artifacts)

    def shutdown(self, *, wait: bool = False) -> None:
        self._executor.shutdown(wait=wait, cancel_futures=False)
